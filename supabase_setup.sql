-- 1. 建表（snake_case 命名，与前端 dataStore 的映射层对应）
create table if not exists public.stories (
  id          bigint generated by default as identity primary key,
  title       text        not null,
  province    text        not null,
  city        text        not null,
  district    text        not null default '城区',
  lng         double precision not null,
  lat         double precision not null,
  nick        text        not null default '佚名',
  views       integer     not null default 0,
  likes       integer     not null default 0,
  time        text        not null,           -- 前端传来的日期字符串 YYYY-MM-DD
  excerpt     text        not null default '',
  content     text        not null,
  created_at  timestamptz not null default now()
);

-- 2. 按创建时间建索引（前端按 created_at 倒序读取）
create index if not exists stories_created_at_idx on public.stories (created_at desc);

-- 3. 启用行级安全（RLS）
alter table public.stories enable row level security;

-- 4. RLS 策略：当前为公开收集模式
--    所有人（含匿名）可读取、可提交；不允许修改和删除（防篡改）
--    若以后接入用户系统想限制"仅作者可删"，再新增带 auth.uid() 的策略
drop policy if exists "stories_select_anon" on public.stories;
create policy "stories_select_anon"
  on public.stories for select
  using (true);

drop policy if exists "stories_insert_anon" on public.stories;
create policy "stories_insert_anon"
  on public.stories for insert
  with check (true);

